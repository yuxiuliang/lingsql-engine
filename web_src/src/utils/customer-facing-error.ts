/**
 * 面向客户的错误文案映射。
 *
 * 背景：后端返回的 message 可能夹带计费与内部实现细节（账本、预留、物理调用、数据源配置等）。
 * 这些内容直接显示给客户，会让人以为产品在乱扣钱或环境没配好，同时也暴露内部实现。
 *
 * 使用范围：**只用于业务用户可见的界面**（聊天、仪表盘、错误页等）。
 * 管理控制台（租户、用户、角色、计费、模型、元数据等页面）应保留后端原文——
 * 操作员需要这些细节来定位问题，兜底反而会掩盖故障原因。
 *
 * @author 余炘洋
 * @date 2026-10-25
 */
const INTERNAL_ERROR_PATTERN = /账本|结算|预留|物理调用|数据源配置|模型已返回|计费|invocation/i;

/**
 * 命中内部术语时使用的兜底文案。
 *
 * @author 余炘洋
 * @date 2026-10-25
 */
export const CUSTOMER_SAFE_ERROR =
  '这次没能算出结果，可以换一种问法再试一次；如果反复出现，请把提问时间告诉我们，我们会去查。';

/**
 * 把后端错误翻译成客户看得懂的话：命中内部术语换成兜底文案，其余保持原样。
 *
 * 保持原样很重要：像「请先修改初始密码」「问题长度不能超过 200 字」这类提示必须能被用户照做，
 * 一律兜底会让人不知道该做什么。
 *
 * @param raw 后端或前端抛出的原始错误消息
 * @return 可直接展示给客户的文案
 * @author 余炘洋
 * @date 2026-10-25
 */
export const toCustomerFacingError = (raw: string): string => {
  return INTERNAL_ERROR_PATTERN.test(raw) ? CUSTOMER_SAFE_ERROR : raw;
};
